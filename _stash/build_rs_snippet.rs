use std::io::Write;

/**
* Generate a small snippet of code that contains the user-changeable configuration entries.
*
* Doing this here (and not in the application source code; a valid alternative) allows steering
* via env.vars. helping to keep application code very short.
*/
#[cfg(false)]   // keep: complex, compared to the value provided, so chose not to use it
fn gen_config_snippet() {
    use std::fs::File;
    let fn_ = std::path::Path::new("tmp/config.in");

    let fps: Option<u8> = {
        option_env!("SLED_FPS").map(|s| {
            s.parse().unwrap_or_else(|err| {
                panic!("❗️Problem parsing env.var. 'SLED_FPS' (expected u8): {}", err);
            })
        })
    };

    let brightness_limit: Option<u8> = {
        option_env!("SLED_BRIGHTNESS_LIMIT").map(|s| {
            s.parse().unwrap_or_else(|err| {
                panic!("❗️Problem parsing env.var. 'SLED_BRIGHTNESS_LIMIT' (expected u8: 0..100): {}", err);
            })
        })
    };
    if let Some(v) = brightness_limit {
        assert!( (0..=100).contains(&v), "❗️'SLED_BRIGHTNESS_LIMIT' out of range: {}, [0,100]", v);
    }

    let snippet = format!(
        r#"// Autogenerated configuration by build.rs
(
    {}, // FPS
    {}, // Brightness limit
)"#,
        fps             .map_or("None".into(), |x| format!("Some({x})")),
        brightness_limit.map_or("None".into(), |x| format!("Some({x})")),
    );

    File::create(&fn_).unwrap().write_all(snippet.as_bytes()).unwrap();
}
